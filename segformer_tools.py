def write_launchers(config: SegFormerExportConfig, segformer_config: Path, segformer_repo_root: Path) -> dict[str, Path]:
    config.out_dir.mkdir(parents=True, exist_ok=True)
    train_path = config.out_dir / "train_segformer_b1.ps1"
    test_path = config.out_dir / "test_segformer_b1.ps1"
    work_dir = config.out_dir / "runs" / "segformer_b1_6cls"
    train_path.write_text(
        "\n".join([
            "$ErrorActionPreference = 'Stop'",
            f"Set-Location {_portable_path(segformer_repo_root)!r}",
            f"& {config.python_executable!r} tools/train.py {_portable_path(segformer_config)!r} --work-dir {_portable_path(work_dir)!r} --gpus 1",
            "",
        ]),
        encoding="utf-8",
    )
    test_path.write_text(
        "\n".join([
            "$ErrorActionPreference = 'Stop'",
            "param([Parameter(Mandatory=$true)][string]$Checkpoint)",
            f"Set-Location {_portable_path(segformer_repo_root)!r}",
            f"& {config.python_executable!r} tools/test.py {_portable_path(segformer_config)!r} $Checkpoint --eval mIoU",
            "",
        ]),
        encoding="utf-8",
    )
    return {"train": train_path, "test": test_path}


def prepare_segformer(config: SegFormerExportConfig, segformer_repo_root: Path) -> dict:
    export = export_mmseg_dataset(config)
    config_path = write_segformer_config(config, export["mmseg_root"])
    launchers = write_launchers(config, config_path, segformer_repo_root)
    result = {
        "mmseg_root": str(export["mmseg_root"]),
        "manifest_path": str(export["manifest_path"]),
        "config_path": str(config_path),
        "train_launcher": str(launchers["train"]),
        "test_launcher": str(launchers["test"]),
        "split_counts": {
            split: payload["count"]
            for split, payload in export["manifest"]["splits"].items()
        },
    }
    summary_path = config.out_dir / "segformer_prepare_summary.json"
    summary_path.write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding="utf-8")
    result["summary_path"] = str(summary_path)
    return result


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Prepare the 6-class tunnel dataset for SegFormer/mmseg training.")
    parser.add_argument("--data-root", type=Path, default=SegFormerExportConfig.data_root)
    parser.add_argument("--out-dir", type=Path, default=SegFormerExportConfig.out_dir)
    parser.add_argument("--segformer-repo-root", type=Path, default=Path(r"C:\Users\26822\Desktop\隧道病害检测\third_party\SegFormer-master"))
    parser.add_argument("--train-n", type=int, default=700)
    parser.add_argument("--val-n", type=int, default=150)
    parser.add_argument("--test-n", type=int, default=150)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--max-iters", type=int, default=160000)
    parser.add_argument("--eval-interval", type=int, default=16000)
    parser.add_argument("--python-executable", default="python")
    parser.add_argument("--pretrained", default=None, help="Optional path to a MiT-B1 pretrained .pth file.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    config = SegFormerExportConfig(
        data_root=args.data_root,
        out_dir=args.out_dir,
        train_n=args.train_n,
        val_n=args.val_n,
        test_n=args.test_n,
        seed=args.seed,
        max_iters=args.max_iters,
        eval_interval=args.eval_interval,
        python_executable=args.python_executable,
        pretrained=args.pretrained,
    )
    result = prepare_segformer(config, args.segformer_repo_root)
    print(json.dumps(result, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
