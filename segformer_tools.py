from __future__ import annotations

import argparse
import json
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

import numpy as np
from PIL import Image

from data_adapter import discover_samples, load_label_mask, split_dataset


CLASS_NAMES = ("background", "simple", "blocky", "pipeline", "vertical", "horizontal")
PALETTE = (
    (0, 0, 0),
    (0, 200, 255),
    (255, 80, 80),
    (140, 90, 255),
    (255, 200, 0),
    (60, 220, 90),
)


def _portable_path(path: Path) -> str:
    return path.resolve().as_posix()


@dataclass(frozen=True)
class SegFormerExportConfig:
    data_root: Path = Path(r"C:\Users\26822\Downloads\data")
    out_dir: Path = Path("experiments/segformer_b1")
    train_n: int = 700
    val_n: int = 150
    test_n: int = 150
    seed: int = 42
    label_mode: str = "multiclass"
    crop_size: int = 512
    samples_per_gpu: int = 2
    workers_per_gpu: int = 2
    max_iters: int = 160000
    eval_interval: int = 16000
    python_executable: str = "python"
    pretrained: Optional[str] = None


def export_mmseg_dataset(config: SegFormerExportConfig) -> dict:
    pairs = discover_samples(config.data_root, label_mode=config.label_mode)
    train, val, test = split_dataset(pairs, config.seed, config.train_n, config.val_n, config.test_n)
    split_pairs = {"train": train, "val": val, "test": test}
    mmseg_root = config.out_dir / "mmseg"
    manifest: dict[str, object] = {
        "data_root": str(config.data_root),
        "mmseg_root": str(mmseg_root),
        "label_mode": config.label_mode,
        "classes": list(CLASS_NAMES),
        "splits": {},
    }

    for split_name, items in split_pairs.items():
        image_dir = mmseg_root / "images" / split_name
        mask_dir = mmseg_root / "masks" / split_name
        image_dir.mkdir(parents=True, exist_ok=True)
        mask_dir.mkdir(parents=True, exist_ok=True)
        records = []
        for image_path_str, mask_path_str in items:
            image_path = Path(image_path_str)
            mask_path = Path(mask_path_str)
            folder_name = image_path.parent.parent.name
            safe_stem = f"{folder_name}_{image_path.stem}"
            image_out = image_dir / f"{safe_stem}{image_path.suffix.lower()}"
            mask_out = mask_dir / f"{safe_stem}.png"

            shutil.copy2(image_path, image_out)
            mask = load_label_mask(mask_path, folder_name, num_classes=len(CLASS_NAMES), label_mode=config.label_mode)
            Image.fromarray(mask.astype(np.uint8), mode="L").save(mask_out)
            records.append({
                "image": str(image_out.relative_to(mmseg_root)),
                "mask": str(mask_out.relative_to(mmseg_root)),
                "source_image": str(image_path),
                "source_mask": str(mask_path),
            })
        manifest["splits"][split_name] = {
            "count": len(records),
            "records": records,
        }

    config.out_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = config.out_dir / "segformer_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    return {
        "mmseg_root": mmseg_root,
        "manifest_path": manifest_path,
        "manifest": manifest,
    }


